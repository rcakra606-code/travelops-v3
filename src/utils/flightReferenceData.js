export function resolveAirlineName(airlineCode = '', fallbackName = '') {
  const code = String(airlineCode || '').trim().toUpperCase();
  if (!code) return String(fallbackName || '').trim();
  const known = IATA_AIRLINES[code];
  if (known) return known;
  return String(fallbackName || '').trim() || code;
}

export function resolveAirportCity(airportCode = '', fallbackCity = '') {
  const code = String(airportCode || '').trim().toUpperCase();
  if (!code) return String(fallbackCity || '').trim();
  if (IATA_AIRPORTS[code]) return IATA_AIRPORTS[code];
  return String(fallbackCity || '').trim();
}

/**
 * Formats an airport into "City (CODE)" — e.g. "Jakarta (CGK)", "Taipei (TPE)".
 */
export function formatAirportDetail(airportCode = '', fallbackCity = '') {
  const code = String(airportCode || '').trim().toUpperCase();
  const city = resolveAirportCity(code, fallbackCity);
  if (city && code) {
    // Avoid duplicating "(CODE)" if fallbackCity already includes it
    if (city.toUpperCase().includes(`(${code})`)) return city;
    return `${city} (${code})`;
  }
  return code || city || '-';
}
